"""---
## 4. Data Preprocessing

Tahapan preprocessing:
1. **Filtering kategori skincare** – inklusikan produk yang relevan
2. **Duplicate removal** – hapus duplikat berdasarkan `product_id`
3. **Missing value handling** – median untuk numerik, modus untuk kategorikal
4. **Parsing semi-structured data** – kolom `average_rating_by_types` dari string ke kolom numerik
5. **Feature engineering** – `repurchase_rate`, `recommendation_rate`, `price_tier`
6. **Outlier detection** – metode IQR pada kolom kritis
7. **Label encoding** – target variabel untuk Random Forest
"""

# ── Step 1: Filter kategori skincare
SKINCARE_KW = [
    'serum','toner','moisturizer','sunscreen','cleanser','mask','cream','lotion',
    'wash','essence','mist','scrub','eye care','skin care','skincare','facial','sheet mask',
    'face','body lotion','body wash','lip balm','eye'
]

def is_skincare(row):
    cat = str(row['default_category']).lower()
    cats = str(row['categories']).lower()
    return any(k in cat or k in cats for k in SKINCARE_KW)

df = df_raw[df_raw.apply(is_skincare, axis=1)].copy()
print(f"Sebelum filter : {len(df_raw):,} produk")
print(f"Setelah filter : {len(df):,} produk skincare")

df.columns = df.columns.str.strip()

# ── Step 2: Duplicate removal
before = len(df)
df = df.drop_duplicates(subset='product_id')
print(f"Duplikat dihapus : {before - len(df)} baris")
print(f"Dataset setelah dedup : {len(df):,} baris")

# ── Step 3: Parsing kolom average_rating_by_types (semi-structured)
def parse_rating_types(s):
    """Parse 'key: val; key: val' atau JSON-like string ke dict."""
    if pd.isna(s):
        return {}
    try:
        pairs = re.findall(r'"?(star_\w+)"?\s*:\s*([\d.]+)', s)
        return {k: float(v) for k, v in pairs}
    except Exception:
        return {}

df['rating_parsed'] = df['average_rating_by_types'].apply(parse_rating_types)

RATING_ASPECTS = {
    'star_effectiveness': 'avg_effectiveness',
    'star_packaging':     'avg_packaging',
    'star_scent':         'avg_scent',
    'star_texture':       'avg_texture',
    'star_value_for_money': 'avg_value_for_money',
}
for src, tgt in RATING_ASPECTS.items():
    df[tgt] = df['rating_parsed'].apply(lambda d: d.get(src, np.nan))

print("Kolom aspek rating berhasil diekstrak:")
print(df[list(RATING_ASPECTS.values())].describe().round(3))

# ── Step 4: Feature Engineering
# Repurchase rate
total_rep = (df['total_repurchase_yes_count']
             + df['total_repurchase_no_count']
             + df['total_repurchase_maybe_count'])
df['repurchase_rate'] = np.where(total_rep > 0,
    df['total_repurchase_yes_count'] / total_rep, np.nan)

# Recommendation rate
df['recommendation_rate'] = np.where(
    df['total_reviews'] > 0,
    df['total_recommended_count'] / df['total_reviews'], np.nan)

# Popularity index
df['popularity_index'] = (
    np.log1p(df['total_reviews']) + np.log1p(df['total_in_wishlist']))

# Price tier dari price_range
def extract_min_price(s):
    if pd.isna(s):
        return np.nan
    # Remove 'Rp ' prefix, then remove all dots (thousands separators).
    # If commas exist as decimal separators, replace them with dots. (not seen in examples but good practice)
    cleaned_s = str(s).replace('Rp ', '').replace('.', '').replace(',', '.')
    nums = re.findall(r'\d+\.?\d*', cleaned_s) # Find numbers potentially with a decimal point
    return float(nums[0]) if nums else np.nan

df['min_price'] = df['price_range'].apply(extract_min_price)
df['price_tier'] = pd.cut(df['min_price'],
    bins=[-1, 100_000, 300_000, np.inf],
    labels=['Low', 'Mid', 'High'])

# Repurchase label (target klasifikasi)
df['repurchase_label'] = pd.cut(df['repurchase_rate'],
    bins=[-0.01, 0.50, 0.75, 1.01],
    labels=['Low', 'Medium', 'High'])

print("Distribusi Repurchase Label (target):")
print(df['repurchase_label'].value_counts())
print(f"\nrepurchase_rate valid: {df['repurchase_rate'].notna().sum():,}")

# ── Step 5: Missing Value Handling
NUMERIC_COLS = ['avg_effectiveness','avg_packaging','avg_scent',
                'avg_texture','avg_value_for_money',
                'recommendation_rate','average_rating','popularity_index']

for col in NUMERIC_COLS:
    # Replace -inf and inf with NaN before filling with median
    df[col] = df[col].replace([np.inf, -np.inf], np.nan)
    median_val = df[col].median()
    n_filled = df[col].isna().sum()
    df[col] = df[col].fillna(median_val)
    if n_filled > 0:
        print(f"  {col}: {n_filled} missing → diisi median ({median_val:.3f})")

print("\nMissing values setelah handling:")
print(df[NUMERIC_COLS].isnull().sum())

# ── Step 6: Outlier Detection (IQR) pada kolom kritis
def detect_outliers_iqr(series, col_name):
    Q1 = series.quantile(0.25)
    Q3 = series.quantile(0.75)
    IQR = Q3 - Q1
    lower, upper = Q1 - 1.5 * IQR, Q3 + 1.5 * IQR
    outliers = ((series < lower) | (series > upper)).sum()
    print(f"  {col_name:30s} | IQR: [{lower:.3f}, {upper:.3f}] | Outlier: {outliers}")

print("Deteksi Outlier (Metode IQR):")
for col in ['average_rating','total_reviews','repurchase_rate','recommendation_rate']:
    detect_outliers_iqr(df[col].dropna(), col)

# Hapus baris yang repurchase_label-nya NaN (untuk modeling)
df_model = df[df['repurchase_label'].notna()].copy()
print(f"\nDataset siap modeling: {len(df_model):,} baris")

