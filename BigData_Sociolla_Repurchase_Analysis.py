"""---
## 6. Data Analytics – Random Forest Classification

Model **Random Forest** digunakan untuk mengklasifikasikan produk ke dalam 3 kelas repurchase intention:
- **Low** : repurchase_rate ≤ 0.50
- **Medium** : 0.50 < repurchase_rate ≤ 0.75
- **High** : repurchase_rate > 0.75

**Fitur (X):** avg_effectiveness, avg_packaging, avg_scent, avg_texture, avg_value_for_money, recommendation_rate, average_rating, popularity_index  
**Target (y):** repurchase_label
"""

# ── Persiapan Fitur dan Target
FEATURES = ['avg_effectiveness','avg_packaging','avg_scent',
            'avg_texture','avg_value_for_money',
            'recommendation_rate','average_rating','popularity_index']
TARGET = 'repurchase_label'

X = df_model[FEATURES].copy()
y = df_model[TARGET].copy()

le = LabelEncoder()
y_enc = le.fit_transform(y)
print("Class mapping:", dict(zip(le.classes_, le.transform(le.classes_))))

# Train-test split 80:20
X_train, X_test, y_train, y_test = train_test_split(
    X, y_enc, test_size=0.2, random_state=42, stratify=y_enc)

# ═══ PERBAIKAN DATA LEAKAGE: Imputasi dilakukan SETELAH split ═══
# Ganti inf/-inf jadi NaN dulu
X_train = X_train.replace([np.inf, -np.inf], np.nan)
X_test = X_test.replace([np.inf, -np.inf], np.nan)

imputer = SimpleImputer(strategy='median')
# Fit dan transform HANYA di data Train
X_train_imputed = imputer.fit_transform(X_train)
# Transform saja (menggunakan median dari Train) di data Test
X_test_imputed = imputer.transform(X_test)

# Konversi kembali ke DataFrame agar nama fitur tetap ada
X_train = pd.DataFrame(X_train_imputed, columns=FEATURES, index=X_train.index)
X_test = pd.DataFrame(X_test_imputed, columns=FEATURES, index=X_test.index)
# ═══════════════════════════════════════════════════════════════

print(f"\nTrain set : {X_train.shape[0]:,} sampel")
print(f"Test set  : {X_test.shape[0]:,} sampel")
print("\nDistribusi kelas train:")
unique, counts = np.unique(y_train, return_counts=True)
for u, c in zip(le.inverse_transform(unique), counts):
    print(f"  {u}: {c}")


# ── Training Random Forest (OPTIMASI PARAMETER)
rf_model = RandomForestClassifier(
    n_estimators=300,          # Ditambah dari 200 agar lebih stabil
    max_depth=None,            # DIHAPUS BATASANNYA, biarkan pohon tumbuh optimal (mengatasi underfitting)
    min_samples_split=5,
    min_samples_leaf=2,
    class_weight='balanced',
    random_state=42,
    n_jobs=-1
)
rf_model.fit(X_train, y_train)
print("Random Forest berhasil dilatih ✓")

from sklearn.metrics import precision_score, recall_score, f1_score, accuracy_score

# Setelah model dilatih, kita prediksi probabilities-nya
y_proba = rf_model.predict_proba(X_test)

# Tentukan threshold manual (contoh: jika kelas Low kemungkinannya >35%, langsung predict Low)
# Angka 0.35 ini bisa Anda mainkan (0.30, 0.40) untuk melihat F1 score terbaik
THRESHOLD_LOW = 0.35

# Dapatkan index kelas Low dari Label Encoder
# Biasanya urutan label encoder adalah alphabetical: High(0), Low(1), Medium(2)
low_idx = list(le.classes_).index('Low')

y_pred_adjusted = []
for probas in y_proba:
    if probas[low_idx] > THRESHOLD_LOW:
        y_pred_adjusted.append(low_idx)
    else:
        # Kalau bukan Low, ambil kelas dengan probabilitas tertinggi
        y_pred_adjusted.append(np.argmax(probas))

y_pred_adjusted = np.array(y_pred_adjusted)

# Sekarang hitung evaluasi menggunakan y_pred_adjusted BUKAN y_pred lama
acc = accuracy_score(y_test, y_pred_adjusted)
prec = precision_score(y_test, y_pred_adjusted, average='weighted')
rec = recall_score(y_test, y_pred_adjusted, average='weighted')
f1 = f1_score(y_test, y_pred_adjusted, average='weighted')

# Bobot custom: Low diberi penalti 5x lipat, Medium 2x lipat, High normal (1x)
custom_weights = {0: 5.0, 1: 1.0, 2: 2.0} # Sesuaikan keynya: 0=High, 1=Low, 2=Medium (cek dari label encoder Anda, urutannya biasanya alphabetical: High=0, Low=1, Medium=2)

rf_model = RandomForestClassifier(
    n_estimators=400,          # Tambah lagi pohonnya
    max_depth=None,            # Biarkan tumbuh
    min_samples_split=2,       # Perkecil dari 5 ke 2 agar pohon lebih detail
    min_samples_leaf=1,        # Perkecil dari 2 ke 1
    class_weight=custom_weights, # Gunakan bobot kustom
    random_state=42,
    n_jobs=-1
)
rf_model.fit(X_train, y_train)
print("Random Forest berhasil dilatih dengan parameter baru ✓")

from sklearn.metrics import precision_score, recall_score, f1_score, accuracy_score, classification_report

# ── Evaluasi Model
y_pred = rf_model.predict(X_test)

# Menghitung metrik keseluruhan (menggunakan average='weighted' untuk multiclass)
acc = accuracy_score(y_test, y_pred)
prec = precision_score(y_test, y_pred, average='weighted')
rec = recall_score(y_test, y_pred, average='weighted')
f1 = f1_score(y_test, y_pred, average='weighted')

# Menampilkan hasil sesuai format yang diinginkan
print("--- EVALUASI MODEL ---")
print(f"Accuracy  : {acc:.4f}")
print(f"Precision : {prec:.4f}")
print(f"Recall    : {rec:.4f}")
print(f"F1-Score  : {f1:.4f}")

print("\nLaporan Klasifikasi Lengkap:")
print(classification_report(y_test, y_pred, target_names=le.classes_))

# ── Feature Importance
feat_imp = pd.Series(rf_model.feature_importances_, index=FEATURES)
feat_imp = feat_imp.sort_values(ascending=False)
print("Feature Importance (Random Forest):")
